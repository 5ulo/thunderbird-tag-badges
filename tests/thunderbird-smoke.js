/* Integration fixture injected into an isolated test copy of the Experiment API. */
(async () => {
  const pause = ms => new Promise(resolve => win.setTimeout(resolve, ms));
  const results = [];
  const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name); };
  const win = Services.wm.getMostRecentWindow("mail:3pane");
  try {
    await pause(1800);
    const pane = win.document.getElementById("tabmail").currentAbout3Pane;
    check(!!pane, "about:3pane available");
    try { MailServices.accounts.localFoldersServer; } catch (_) { MailServices.accounts.createLocalMailAccount(); }
    const server = MailServices.accounts.localFoldersServer;
    const root = server.rootFolder;
    if (!root.containsChildNamed("BadgeSmoke")) root.createSubfolder("BadgeSmoke", null);
    await pause(1600);
    const folder = root.getChildNamed("BadgeSmoke");
    folder.QueryInterface(Ci.nsIMsgLocalMailFolder).addMessage("From - Wed Nov 25 12:00:00 2026\r\nFrom: test@example.invalid\r\nTo: demo@example.invalid\r\nSubject: Badge smoke test\r\nMessage-ID: <badge-smoke@example.invalid>\r\nDate: Wed, 25 Nov 2026 12:00:00 +0100\r\n\r\nTest message.\r\n");
    const hdr = [...folder.messages][0];
    MailServices.tags.addTagForKey("smoke-custom", "Vlastný štítok", "#ffcc00", "");
    const tags = MailServices.tags.getAllTags();
    hdr.setStringProperty("keywords", tags[0].key + " smoke-custom");
    pane.displayFolder(folder.URI);
    await pause(1000);
    this.settings = this.shared.TagBadgeSettings.normalize();
    Services.prefs.setIntPref("mail.threadpane.listview", 1); pane.threadPane.updateThreadView("table");
    await pause(500);
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    let row = pane.document.querySelector('#threadTree tr[is="thread-row"]');
    check(!!row, "table row exists");
    if (row.querySelectorAll(".tb-tag-badge").length !== 2) results.push({documents:this.documents.size, keywords:hdr.getStringProperty("keywords"), properties:row.dataset.properties});
    check(row.querySelectorAll('.tb-tag-badge').length === 2, "multiple system/custom table badges");
    check(row.querySelector('.subject-line').children[1].classList.contains('tb-tag-badges'), "badges before subject");
    const line = row.querySelector('.subject-line');
    const subject = line.querySelector(':scope > span');
    const originalSubject = subject.textContent;
    subject.textContent = 'Veľmi dlhý predmet správy '.repeat(40);
    line.style.width = '360px';
    line.style.flex = '0 0 360px';
    await pause(1600);
    const assertBadgesFit = name => {
      const group = row.querySelector('.tb-tag-badges');
      const bounds = group.getBoundingClientRect();
      const last = group.lastElementChild.getBoundingClientRect();
      if (!(bounds.width >= group.scrollWidth - 1 && last.right <= bounds.right + 1)) results.push({name, width:bounds.width, scroll:group.scrollWidth, html:group.outerHTML, children:[...group.children].map(b => ({hidden:b.hidden,width:b.getBoundingClientRect().width}))});
      check(bounds.width >= group.scrollWidth - 1 && last.right <= bounds.right + 1, name);
    };
    assertBadgesFit("long subject preserves both complete badges before subject");
    this.settings.position = "after";
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    assertBadgesFit("long subject preserves both complete badges after subject");
    check(row.querySelector('.tb-tag-badges').getBoundingClientRect().right <= line.getBoundingClientRect().right + 1, "badges after long subject stay inside subject line");
    subject.textContent = originalSubject;
    this.settings.tableMaxTags = 1;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(row.querySelectorAll('.tb-tag-badge').length === 1, "maximum tag limit");
    check(row.querySelector('.subject-line').lastElementChild.classList.contains('tb-tag-badges'), "badges after subject");
    check(row.querySelector('.tb-tag-more').textContent === '+1' && !row.querySelector('.tb-tag-more').hidden, "count limit shows +1");
    this.settings.tableMaxTags = 0;
    this.settings.order = "priority";
    this.settings.priority = ["smoke-custom"];
    this.settings.size = "normal";
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(row.querySelector('.tb-tag-badge').textContent === "Vlastný štítok", "custom tag priority applies");
    const normalHeight = row.querySelector('.tb-tag-badge').getBoundingClientRect().height;
    this.settings.size = "compact";
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(row.querySelector('.tb-tag-badge').getBoundingClientRect().height < normalHeight, "compact badges smaller than normal");
    line.style.width = '120px';
    line.style.flex = '0 0 120px';
    await pause(1800);
    const group = row.querySelector('.tb-tag-badges');
    const visible = [...group.querySelectorAll('.tb-tag-badge')].filter(b => !b.hidden);
    const counter = group.querySelector('.tb-tag-more');
    check(!counter.hidden && counter.textContent === `+${2 - visible.length}`, "narrow column summarizes hidden tags");
    const bounds = group.getBoundingClientRect();
    check(bounds.width > 0 && [...visible, counter].every(b => {
      const r = b.getBoundingClientRect(); return r.left >= bounds.left - 1 && r.right <= bounds.right + 1;
    }), "narrow column displays only whole badges and counter");
    line.style.width = '400px';
    line.style.flex = '0 0 400px';
    await pause(1800);
    check([...row.querySelectorAll('.tb-tag-badge')].every(b => !b.hidden) && row.querySelector('.tb-tag-more').hidden, "widening restores badges automatically");
    line.style.removeProperty('width');
    line.style.removeProperty('flex');
    this.settings.tableEnabled = false;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(!row.querySelector('.tb-tag-badges'), "table toggle removes badges");
    this.settings.tableEnabled = true;
    this.settings.tableMaxTags = 0;
    Services.prefs.setIntPref("mail.threadpane.listview", 0); pane.threadPane.updateThreadView("cards");
    await pause(500);
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    row = pane.document.querySelector('#threadTree tr[is="thread-card"]');
    check(!!row, "card exists");
    check(row.querySelectorAll('.tb-tag-badge').length === 2, "multiple card badges");
    check(pane.getComputedStyle(row.querySelector('.thread-card-tags-info, thread-card-tags')).display === 'none', "native tag icons hidden");
    check(!!row.querySelector(':is(.thread-card-last-row, .thread-card-dynamic-row) .tb-tag-badges'), "badges in bottom card row");
    if (row.querySelector('thread-card-tags')) {
      for (const count of [2, 3]) {
        Services.prefs.setIntPref('mail.threadpane.cardsview.rowcount', count);
        pane.threadPane.updateThreadItemSize();
        await pause(500);
        for (const state of this.documents.values()) state.schedule();
        await pause(1600);
        row = pane.document.querySelector('#threadTree tr[is="thread-card"]');
        const info = row.querySelector('.thread-card-icon-info').getBoundingClientRect();
        const star = row.querySelector('.button-star').getBoundingClientRect();
        const group = row.querySelector('.tb-tag-badges').getBoundingClientRect();
        check(group.width > 0 && Math.abs(star.right-info.right) <= 2 && star.left-group.right >= -1 && star.left-group.right <= 14, `modern ${count}-row cards keep badges beside right-aligned star`);
        check(pane.getComputedStyle(row.querySelector('thread-card-tags')).display === 'none', `modern ${count}-row cards hide native tags`);
      }
    }
    MailServices.tags.setTagForKey("smoke-custom", "Premenovaný štítok");
    await pause(1600);
    check([...row.querySelectorAll('.tb-tag-badge')].some(b => b.textContent === "Premenovaný štítok"), "tag rename updates automatically");
    this.settings.pill = false;
    this.settings.radius = 7;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(pane.getComputedStyle(row.querySelector('.tb-tag-badge')).borderTopLeftRadius === '7px', "custom border radius");
    check(pane.getComputedStyle(row).getPropertyValue('--tag-color').trim() === '', "native row tag colors suppressed");
    this.settings.nativeRowColors = true;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(pane.getComputedStyle(row).getPropertyValue('--tag-color').trim() !== '', "native row tag colors restored");
    this.settings.cardMaxTags = 1;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(row.querySelectorAll('.tb-tag-badge').length === 1 && row.querySelector('.tb-tag-more').textContent === '+1', "card limit independent from table limit");
    this.settings.cardEnabled = false;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(!row.querySelector('.tb-tag-badges'), "card toggle removes badges");
    check(pane.getComputedStyle(row.querySelector('.thread-card-tags-info, thread-card-tags')).display !== 'none', "card toggle restores native icons");
    const tabmail = win.document.getElementById("tabmail");
    const optionsTab = tabmail.openTab("contentTab", {url:this.context.extension.getURL("options/options.html"), triggeringPrincipal:this.context.extension.principal});
    for (let i = 0; i < 100 && !this.optionsResult; i++) await pause(100);
    check(this.optionsResult?.ok, this.optionsResult?.ok ? "options page saves new settings" : `options page failed: ${this.optionsResult?.error || "no result"}`);
    check(this.optionsResult.count === MailServices.tags.getAllTags().length, "options loads actual system and custom tags");
    await pause(500);
    check(this.settings.tableMaxTags === 2 && this.settings.cardMaxTags === 1 && this.settings.size === 'normal' && this.settings.priority[0] === this.optionsResult.firstKey, "saved options apply to active message views");
    tabmail.closeTab(optionsTab);
    const manager = await win.openAddonsMgr('addons://detail/' + encodeURIComponent(this.context.extension.id));
    await pause(1200);
    const findDetails = doc => {
      const host = doc.querySelector('addon-card[addon-id="' + this.context.extension.id + '"] .addon-detail-description');
      if (host) return host;
      for (const browser of doc.querySelectorAll('browser, iframe')) {
        try { if (browser.contentDocument) { const found = findDetails(browser.contentDocument); if (found) return found; } } catch (_) {}
      }
      return null;
    };
    const descriptionHost = findDetails(manager.document);
    check(!!descriptionHost?.querySelector('.tb-addon-description'), "localized full description appears in native Details tab");
    check(descriptionHost.textContent.includes(this.detailsDescription.split('\n\n')[0]), "Details description uses selected locale text");
    check(descriptionHost.querySelectorAll('p').length === 4, "Details description contains feature privacy and compatibility information");
    const detailsAddon = this.detailsAddon;
    this.close();
    check(!detailsAddon.getFullDescription && !descriptionHost.querySelector('.tb-addon-description'), "description hook and inserted text cleaned up on disable");
    check(!pane.document.querySelector('.tb-no-tag-colors, .tb-tag-badges, .tb-card-badges, .tb-table-badges'), "cleanup restores native UI");
    await IOUtils.writeUTF8(SMOKE_RESULT_PATH, JSON.stringify({ok:true,results}));
  } catch (error) {
    await IOUtils.writeUTF8(SMOKE_RESULT_PATH, JSON.stringify({ok:false,results,error:String(error),stack:error.stack}));
  }
})();
