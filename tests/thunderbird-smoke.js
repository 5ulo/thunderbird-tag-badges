/* Integration fixture injected into an isolated test copy of the Experiment API. */
(async () => {
  const pause = ms => new Promise(resolve => win.setTimeout(resolve, ms));
  const results = [];
  const check = (ok, name) => { if (!ok) throw new Error(name); results.push(name); };
  const win = Services.wm.getMostRecentWindow("mail:3pane");
  try {
    await pause(1800);
    const pane = win.document.getElementById("tabmail").currentAbout3Pane;
    check(!!pane, "about:3pane available");
    try { MailServices.accounts.localFoldersServer; } catch (_) { MailServices.accounts.createLocalMailAccount(); }
    const server = MailServices.accounts.localFoldersServer;
    const root = server.rootFolder;
    if (!root.containsChildNamed("BadgeSmoke")) root.createSubfolder("BadgeSmoke", null);
    await pause(1600);
    const folder = root.getChildNamed("BadgeSmoke");
    folder.QueryInterface(Ci.nsIMsgLocalMailFolder).addMessage("From - Wed Nov 25 12:00:00 2026\r\nFrom: test@example.invalid\r\nTo: demo@example.invalid\r\nSubject: Badge smoke test\r\nMessage-ID: <badge-smoke@example.invalid>\r\nDate: Wed, 25 Nov 2026 12:00:00 +0100\r\n\r\nTest message.\r\n");
    const hdr = [...folder.messages][0];
    MailServices.tags.addTagForKey("smoke-custom", "Vlastný štítok", "#ffcc00", "");
    const tags = MailServices.tags.getAllTags();
    hdr.setStringProperty("keywords", tags[0].key + " smoke-custom");
    pane.displayFolder(folder.URI);
    await pause(1000);
    this.settings = this.shared.TagBadgeSettings.normalize();
    pane.threadPane.updateThreadView("table");
    await pause(500);
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    let row = pane.document.querySelector('#threadTree tr[is="thread-row"]');
    check(!!row, "table row exists");
    if (row.querySelectorAll(".tb-tag-badge").length !== 2) results.push({documents:this.documents.size, keywords:hdr.getStringProperty("keywords"), properties:row.dataset.properties});
    check(row.querySelectorAll('.tb-tag-badge').length === 2, "multiple system/custom table badges");
    check(row.querySelector('.subject-line').children[1].classList.contains('tb-tag-badges'), "badges before subject");
    const line = row.querySelector('.subject-line');
    const subject = line.querySelector(':scope > span');
    const originalSubject = subject.textContent;
    subject.textContent = 'Veľmi dlhý predmet správy '.repeat(40);
    line.style.width = '360px';
    line.style.flex = '0 0 360px';
    await pause(1600);
    const assertBadgesFit = name => {
      const group = row.querySelector('.tb-tag-badges');
      const bounds = group.getBoundingClientRect();
      const last = group.lastElementChild.getBoundingClientRect();
      check(bounds.width >= group.scrollWidth - 1 && last.right <= bounds.right + 1, name);
    };
    assertBadgesFit("long subject preserves both complete badges before subject");
    this.settings.position = "after";
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    assertBadgesFit("long subject preserves both complete badges after subject");
    check(row.querySelector('.tb-tag-badges').getBoundingClientRect().right <= line.getBoundingClientRect().right + 1, "badges after long subject stay inside subject line");
    subject.textContent = originalSubject;
    line.style.removeProperty('width');
    line.style.removeProperty('flex');
    this.settings.maxTags = 1;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(row.querySelectorAll('.tb-tag-badge').length === 1, "maximum tag limit");
    check(row.querySelector('.subject-line').lastElementChild.classList.contains('tb-tag-badges'), "badges after subject");
    this.settings.tableEnabled = false;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(!row.querySelector('.tb-tag-badges'), "table toggle removes badges");
    this.settings.tableEnabled = true;
    this.settings.maxTags = 0;
    pane.threadPane.updateThreadView("cards");
    await pause(500);
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    row = pane.document.querySelector('#threadTree tr[is="thread-card"]');
    check(!!row, "card exists");
    check(row.querySelectorAll('.tb-tag-badge').length === 2, "multiple card badges");
    check(pane.getComputedStyle(row.querySelector('.thread-card-tags-info')).display === 'none', "native tag icons hidden");
    check(!!row.querySelector('.thread-card-last-row .tb-tag-badges'), "badges in bottom card row");
    MailServices.tags.setTagForKey("smoke-custom", "Premenovaný štítok");
    await pause(1600);
    check([...row.querySelectorAll('.tb-tag-badge')].some(b => b.textContent === "Premenovaný štítok"), "tag rename updates automatically");
    this.settings.pill = false;
    this.settings.radius = 7;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(pane.getComputedStyle(row.querySelector('.tb-tag-badge')).borderTopLeftRadius === '7px', "custom border radius");
    check(pane.getComputedStyle(row).getPropertyValue('--tag-color').trim() === '', "native row tag colors suppressed");
    this.settings.nativeRowColors = true;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(pane.getComputedStyle(row).getPropertyValue('--tag-color').trim() !== '', "native row tag colors restored");
    this.settings.cardEnabled = false;
    for (const s of this.documents.values()) s.schedule();
    await pause(1600);
    check(!row.querySelector('.tb-tag-badges'), "card toggle removes badges");
    check(pane.getComputedStyle(row.querySelector('.thread-card-tags-info')).display !== 'none', "card toggle restores native icons");
    this.close();
    check(!pane.document.querySelector('.tb-no-tag-colors, .tb-tag-badges, .tb-card-badges, .tb-table-badges'), "cleanup restores native UI");
    await IOUtils.writeUTF8(SMOKE_RESULT_PATH, JSON.stringify({ok:true,results}));
  } catch (error) {
    await IOUtils.writeUTF8(SMOKE_RESULT_PATH, JSON.stringify({ok:false,results,error:String(error),stack:error.stack}));
  }
})();
